test("false prose explanations remain GEval counterexamples even with a mechanically valid graph and tail", (t) => {
  const { capture } = fixture(t);
  const samples = [
    {
      id: "independent-concept",
      original: "No result of either consumer becomes an eligibility precondition.",
      replacement:
        "Eligibility C is independent by name, but it grants eligibility only after Pricing confirms its discount succeeded. Keep the displayed graph without this return dependency.",
    },
    {
      id: "existing-owner",
      original:
        "The proposed return edge is explicitly rejected as an ownership mistake; no required guarantee is removed or renamed.",
      replacement:
        "Keep active-and-verified eligibility delegated from Identity to Workspace. Rename identity -> workspace to a Related link so dependsOn is acyclic; no definition or guarantee needs to move.",
    },
    {
      id: "inseparable-merge",
      original: "Recommend merge.",
      replacement:
        "Call the wallet solution existing-owner orientation. Move every credit obligation into debit and delete credit, leaving no independent extra in B; this is different from a merge.",
    },
    {
      id: "single-batch",
      original: "The complete batch is ready for one reply by question ID.",
      replacement:
        "Only q-commerce is ready for the user's answer. Pause now and investigate Wallet, Identity/Workspace and Support in later turns after that approval.",
    },
    {
      id: "graphs-and-mutation-scope",
      original:
        "Removal needs explicit scope approval and a fresh destination/reference check because another contributor could add references.",
      replacement:
        "The wallet option label alone approves deletion of any related files; omit the exact removal paths and original failure-guarantee ownership trace from review.",
    },
  ];
  for (const sample of samples) {
    assert.ok(reportBody().includes(sample.original));
    const text = output(reportBody().replace(sample.original, sample.replacement));
    const { checks, evidence } = capture(text);
    assert.ok(
      checks.every((c) => c.pass),
      "local guards must not pretend to understand arbitrary prose",
    );
    const input = deepEvalInput({ ...scenario, turns: evidence.turns }, evidence);
    assert.deepEqual(JSON.parse(input.expectedOutput).obligations, obligations);
    assert.ok(obligations.some((obligation) => obligation.id === sample.id));
    assert.equal(JSON.parse(input.actualOutput).resultingFiles[REPORT], text);
    assert.deepEqual(JSON.parse(input.actualOutput).replies, [text]);
  }
});

test("unauthorized apply, delete, move, index/status change and synthetic owner writes are rejected even when restored", async (t) => {
  const existing = "docs/adr/wallet/0002-credit.md";
  for (const mutant of [
    "apply",
    "delete",
    "move",
    "index",
    "status",
    "placeholder",
    "source-attempt",
    "extra-report",
  ])
    await t.test(mutant, (t) => {
      const { tools, capture } = fixture(t);
      const put = (file, content) => tools.call("write_file", { path: file, content });
      if (mutant === "apply" || mutant === "status") {
        put(
          existing,
          mutant === "status"
            ? fixtureFiles[existing].replace("\nProposed\n", "\nAccepted (2026-10-01)\n")
            : "# Applied the recommendation without approval\n",
        );
        put(existing, fixtureFiles[existing]);
      } else if (mutant === "delete") {
        tools.call("delete_file", { path: existing });
        put(existing, fixtureFiles[existing]);
      } else if (mutant === "move") {
        const moved = "docs/adr/wallet/0002-moved.md";
        tools.call("move_file", { from: existing, to: moved });
        tools.call("move_file", { from: moved, to: existing });
      } else if (mutant === "index") {
        put("docs/adr/.mapping.json", '{"categories":{}}');
        put("docs/adr/.mapping.json", fixtureFiles["docs/adr/.mapping.json"]);
      } else if (mutant === "placeholder" || mutant === "extra-report") {
        const extra =
          mutant === "placeholder"
            ? "docs/adr/common/0001-placeholder.md"
            : "docs/reports/delivery-question.md";
        put(extra, "# Unapproved extra document\n");
        tools.call("delete_file", { path: extra });
      } else {
        assert.throws(() => put("packages/wallet/transfer.mjs", "// unauthorized change"));
      }
      const { checks } = capture();
      assert.equal(checks.find((c) => c.label.startsWith("all mutations")).pass, false);
      assert.equal(
        checks.find((c) => c.label.startsWith("original inputs")).pass,
        true,
        "restored final bytes cannot hide unauthorized events",
      );
    });
});
