function output(body = reportBody(), rows = tailRows()) {
  return `${body}\n\n=== EVAL-VERDICT: PENDING ===\n=== EVAL-FINDINGS ===\n${rows.map((r) => `${r.tag} | ${r.summary}`).join("\n")}\n=== EVAL-END ===\n`;
}

function fixture(t) {
  const folder = mkdtempSync(path.join(tmpdir(), "import-cycle-options-"));
  t.after(() => rmSync(folder, { recursive: true, force: true }));
  const root = path.join(folder, "workspace");
  createWorkspace(root, fixtureFiles, PLUGIN_ROOT);
  const prompt = scenario.build(root);
  const before = snapshot(root);
  const logPath = path.join(folder, "events.jsonl");
  const tools = makeTools({
    root,
    pluginRoot: PLUGIN_ROOT,
    logPath,
    turn: 1,
    artifactPaths: scenario.artifactPaths,
  });
  for (const file of Object.keys(fixtureFiles)) tools.call("read_file", { path: file });
  const events = () => readFileSync(logPath, "utf8").trim().split("\n").map(JSON.parse);
  function capture(text = output()) {
    tools.call("write_file", { path: REPORT, content: text });
    const input = { dir: root, events: events(), tail: parseTail(text), output: text };
    return {
      checks: deterministicScore(input),
      evidence: {
        before,
        after: snapshot(root),
        events: input.events,
        replies: [text],
        turns: [prompt],
        referenceDate: "2026-10-01",
      },
    };
  }
  return { root, prompt, tools, capture };
}

test("cycle scenario loads the current conditional reference and is catalogued with fixed semantic obligations", async (t) => {
  const { prompt } = fixture(t);
  const reference = readFileSync(path.join(PLUGIN_ROOT, CYCLE_REFERENCE), "utf8");
  assert.ok(prompt.includes(reference));
  assert.equal(prompt.split(`# Loaded reference: ${CYCLE_REFERENCE}`).length, 2);
  for (const obligation of obligations)
    assert.ok(
      !prompt.includes(obligation.text),
      "scorer expectations are not copied into the target prompt",
    );
  const registered = (await catalog()).find((entry) => entry.id === scenario.name);
  assert.equal(registered.type, "classification");
  assert.equal(registered.score, deterministicScore);
  assert.deepEqual(registered.semanticObligations, obligations);
  assert.equal(registered.supplementalChecks, true);
  assert.deepEqual(
    [
      ...scenarioNamesForChangedPaths(
        [`plugins/adr-writer/${CYCLE_REFERENCE}`],
        [scenario, { name: "sync-unrelated" }],
      ),
    ],
    [scenario.name],
  );
});

test("raw fixture is valid for local tools and positive batch evidence passes mechanical gates", (t) => {
  const { tools, capture } = fixture(t);
  for (const kind of ["policy-tests", "structure", "invariants"]) {
    const result = tools.call("run_check", { kind });
    assert.equal(result.exitCode, 0, `${kind}: ${result.stdout}${result.stderr}`);
  }
  const { checks, evidence } = capture();
  assert.ok(
    checks.every((c) => c.pass),
    JSON.stringify(checks),
  );
  const input = deepEvalInput({ ...scenario, turns: evidence.turns }, evidence);
  assert.deepEqual(JSON.parse(input.expectedOutput).obligations, obligations);
  assert.equal(JSON.parse(input.actualOutput).resultingFiles[REPORT], output());
});

test("missing or invented fourth option and split/omitted batch records are rejected mechanically", (t) => {
  const { capture } = fixture(t);
  for (const mutate of [
    (rows) => rows.filter((r) => r.tag !== "commerce-owner"),
    (rows) => [
      ...rows,
      { tag: "commerce-interface", summary: "Introduce an implementation interface" },
    ],
    (rows) => [...rows, { tag: "q-commerce", summary: "Ask Delivery separately" }],
    (rows) => rows.filter((r) => r.tag !== "q-retention"),
    (rows) => rows.filter((r) => !r.tag.startsWith("access-") && r.tag !== "q-access"),
  ]) {
    const { checks } = capture(output(reportBody(), mutate(tailRows())));
    assert.equal(checks.find((c) => c.label.startsWith("all three comparisons")).pass, false);
  }
});

