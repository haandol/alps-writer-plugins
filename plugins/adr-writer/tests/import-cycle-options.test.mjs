function tailRows() {
  return [
    ...Object.entries(explanations).flatMap(([group, options]) =>
      Object.entries(options).map(([option, reason]) => ({
        tag: `${group}-${option}`,
        summary: reason,
      })),
    ),
    ...Object.entries(questions).map(([tag, summary]) => ({ tag, summary })),
  ];
}

